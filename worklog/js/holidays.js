/**
 * 合并优先级：用户自定义 > 远程更新 > 内置。
 * 用户条目 hidden=true 时表示隐藏该日期的内置/远程数据。
 */
export function buildHolidayMap(user = [], remote = []) {
  const map = new Map()
  for (const h of BUILTIN_HOLIDAYS) map.set(h.date, h)
  for (const h of remote) map.set(h.date, { ...h, source: 'remote' })
  for (const h of user) {
    if (h.hidden) map.delete(h.date)
    else map.set(h.date, { ...h, source: h.source || 'user' })
  }
  return map
}

export function holidayListForYear(map, year) {
  return [...map.values()]
    .filter((h) => Number(h.date.slice(0, 4)) === year)
    .sort((a, b) => a.date.localeCompare(b.date))
}
